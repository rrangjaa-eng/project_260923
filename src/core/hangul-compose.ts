export function composeHangul(initial: number, medial: number, final: number): string {
  if (![initial,medial,final].every(Number.isInteger) || initial < 0 || initial >= 19 || medial < 0 || medial >= 21 || final < 0 || final >= 28) throw new RangeError('Invalid Hangul indices');
  return String.fromCharCode(0xac00 + (initial * 21 + medial) * 28 + final);
}
